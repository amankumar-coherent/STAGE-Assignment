"""Generated run report (sample_run/final_report.md). Every number comes from this run's artifacts."""
from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any

from .impact_reporter import interpret, pct, pp
from .loader import read_jsonl


def render_final(out: Path, summary, result, itt, pilot, seeds, sim, policy, outcomes, dq, world, seed: str,
                 wall_s: float) -> str:
    lat = summary["latency"]
    decisions = list(read_jsonl(out / "decisions.jsonl"))
    actions = world.store.all_actions()
    arms = dict(world.arms.items())
    holdout_actions = sum(1 for a in actions if arms.get(a["user_id"]) != "agent")
    by_status = Counter(d["status"] for d in decisions)
    by_action = Counter(d["action"] for d in decisions)
    act_status = Counter((a["type"], a["status"]) for a in actions)
    failed_checks = Counter(f["check"].split(":", 1)[-1] for d in decisions for f in d["checks"]["failed"])
    repairs = sum(len(d["repairs"]) for d in decisions)
    reasons = Counter()
    for d in decisions:
        if d["status"] in ("ABSTAINED", "BLOCKED_BY_VERIFIER"):
            r = d["no_action_reason"] or ""
            key = ("stale trigger" if r.startswith("stale trigger") else
                   "dialect unknown/without content" if r.startswith("cannot act") else
                   "page already live" if "already live" in r else
                   "no eligible measurable goal" if r.startswith("no eligible") else
                   "state store unavailable (fail closed)" if "fail closed" in r else
                   "verifier blocked" if d["status"] == "BLOCKED_BY_VERIFIER" else r[:60])
            reasons[key] += 1
    res = Counter((o["arm"], o["result"]) for o in outcomes)
    attrib = Counter(o["attribution"] for o in outcomes if o["result"] == "succeeded")
    goals_new = Counter((d["arm"], d["goal"]["id"]) for d in decisions if d["goal"].get("selection") == "new")
    p = itt["primary"]
    L = ["# Final run report (generated)", "",
         f"Generated by `python run.py` in {wall_s:.0f} s. Mock model provider, no network, no API key. "
         f"Headline simulator seed `{seed}`.", "",
         "## Replay", "",
         f"* Trigger deliveries processed: **{lat['triggers_processed']}** "
         f"(decisions written incl. withdrawal repairs: {summary['decisions']}).",
         f"* Decisions by status: {dict(sorted(by_status.items()))}.",
         f"* Decision actions: {dict(by_action.most_common())}.",
         f"* Actions by type/status: { {f'{k[0]}:{k[1]}': v for k, v in sorted(act_status.items())} }.",
         f"* Abstention reasons (agent arm): {dict(reasons.most_common())}.",
         f"* New goals by arm: {dict(sorted(goals_new.items(), key=lambda kv: (kv[0][0], str(kv[0][1]))))}.", "",
         "## Latency (virtual clock; see latency_report.json for semantics)", "",
         f"* All decisions: median {lat['all_decisions'].get('median_ms')} ms, p95 {lat['all_decisions'].get('p95_ms')} ms, "
         f"p99 {lat['all_decisions'].get('p99_ms')} ms, max {lat['all_decisions'].get('max_ms')} ms.",
         f"* Published decisions: median {lat['published_decisions'].get('median_ms')} ms, p95 "
         f"{lat['published_decisions'].get('p95_ms')} ms, max {lat['published_decisions'].get('max_ms')} ms.",
         f"* Over 60 s: {lat['over_60s']['count']} ({lat['over_60s']['pct']}%); over 5 min: {lat['over_5min']}. "
         f"Real compute only: median {lat['compute_only'].get('median_ms')} ms, max {lat['compute_only'].get('max_ms')} ms.",
         f"* Fallbacks: {lat['fallbacks']}; degraded decisions: {lat['degraded_decisions']}; model statuses: "
         f"{lat['model_status_counts']}; store gate: {lat['store_gate']}.",
         f"* Replay wall clock on this machine: {lat['replay_wall_clock_s']} s.", "",
         "## Surprises and how they were handled", ""]
    for c in result["controls"]:
        L.append(f"* `{c['type']}` at {c['at']}: " + ", ".join(
            f"{k}={len(v) if isinstance(v, list) else v}" for k, v in c.items() if k not in ("type", "at", "detail")))
    for f in lat["model_faults"]:
        L.append(f"* model fault `{f['fault']}` on {f['trigger_event_id'][:8]} ({f['user_id']}): model hit "
                 f"{f['model_calls_hit']}x, status `{f['model_status']}`, goal {f['goal']}, decision {f['status']}"
                 + (f" - {f['note']}" if f["note"] else ""))
    L += [f"* Duplicate trigger deliveries ignored: {lat['counters'].get('duplicate_triggers', 0)}; duplicate live "
          f"events: {lat['counters'].get('duplicate_live_events', 0)}; stale triggers: {lat['stale_triggers']}.",
          f"* Pending actions cancelled during replay: {lat['counters'].get('cancelled_actions', 0)}; end-of-replay "
          f"revalidation: {lat['final_revalidation']}.", "",
          "## Safety", "",
          f"* Actions on holdout or unknown users: **{holdout_actions}** (simulator holdout_actions_ignored: "
          f"{sim.get('counts', {}).get('holdout_actions_ignored', 0)}).",
          f"* Simulator policy_problem_count: **{sim.get('policy_problem_count')}**. Independent export audit: {policy}.",
          f"* Verifier failed checks across all decisions: {dict(failed_checks.most_common()) or 'none'}; repairs "
          f"(actions dropped before publication): {repairs}.",
          f"* Instruction-like catalogue text quarantined: {list(dq['catalogue']['instruction_like_descriptions'])}.", "",
          "## Goal outcomes (judged from simulator events)", "",
          f"* Results by arm: {dict(sorted(res.items()))}.",
          f"* Attribution of successes: {dict(attrib)}.", "",
          "## Impact (randomized ITT; details in impact_report.md)", "",
          f"* Agent {p['agent_k']}/{p['agent_n']} ({pct(p['agent_rate'])}) vs holdout {p['holdout_k']}/{p['holdout_n']} "
          f"({pct(p['holdout_rate'])}): **{pp(p['diff_pp'])}**, 95% CI [{p['ci_lo_pp']:+.2f}, {p['ci_hi_pp']:+.2f}] pp. "
          f"{interpret(p)[0].upper() + interpret(p)[1:]}.",
          "* Seeds: " + "; ".join(f"`{s['seed']}` {pp(s['primary']['diff_pp'])}" for s in seeds) + "."]
    for r in itt["secondary"]:
        L.append(f"* {r['label']}: {pct(r['agent_rate'])} vs {pct(r['holdout_rate'])}, {pp(r['diff_pp'])} "
                 f"[{r['ci_lo_pp']:+.2f}, {r['ci_hi_pp']:+.2f}]")
    L += ["", "## Pilot audit", "",
          f"* Report method (served vs everyone else): {pct(pilot['flawed']['agent_rate'])} vs "
          f"{pct(pilot['flawed']['holdout_rate'])} ({pp(pilot['flawed']['diff_pp'])}).",
          f"* Randomized ITT: {pct(pilot['itt']['agent_rate'])} vs {pct(pilot['itt']['holdout_rate'])}, "
          f"{pp(pilot['itt']['diff_pp'])} [{pilot['itt']['ci_lo_pp']:+.2f}, {pilot['itt']['ci_hi_pp']:+.2f}].",
          f"* Holdout users with the served users' goal mix: {pct(pilot['served_expected_without_agent'])} "
          "(selection explains the gap).", "",
          "## Reproduce", "", "```", "python run.py                      # this report", "python -m unittest discover -s tests -v",
          "```", ""]
    return "\n".join(L)
